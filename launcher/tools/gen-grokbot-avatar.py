#!/usr/bin/env python3
"""Generates launcher/.../GrokbotAvatarData.java from the vendored copy of Tom Ballard's MIT avatar code
(webos/app/vendor/grokbot/grokbot-avatar.js: his qml/shapes.js, palette.js and face.js, v0.1.0, commit a2efb00).

The Java side gets the same numbers the web side draws with: his 14 shape outlines, their eyes, the pebble's
stem, the look table, the alias names and the 11-colour palette. No Android build is needed to regenerate it.

  python3 launcher/tools/gen-grokbot-avatar.py          # write the Java file
  python3 launcher/tools/gen-grokbot-avatar.py --check  # exit 1 if the Java file is out of date
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
VENDOR = ROOT / "webos/app/vendor/grokbot/grokbot-avatar.js"
OUT = ROOT / "launcher/app/src/main/java/com/omarchytv/home/GrokbotAvatarData.java"

DUMP = r"""
const fs = require("fs"); const window = {};
eval(fs.readFileSync(process.argv[1], "utf8"));
const S = window.GrokbotShapes, P = window.GrokbotPalette, F = window.GrokbotFace;
const shapes = S.NAMES.map(n => { const s = S.SHAPES[n], l = S.look(n); return {
  name: n, points: [].concat(...s.points), stem: s.stem ? [].concat(...s.stem) : null,
  eyes: [].concat(...s.eyes.map(e => [e.x, e.y, e.length, e.width, e.angle])),
  face: l.face, size: l.size, fit: l.fit }; });
const colors = P.NAMES.map(n => ({ name: n, fill: P.COLORS[n].fill, darkFill: P.COLORS[n].darkFill || "", eye: P.COLORS[n].eye }));
const poses = Object.keys(F.POSES).map(k => ({ name: k, tilt: F.POSES[k].tilt, height: F.POSES[k].height, open: F.POSES[k].open }));
console.log(JSON.stringify({ shapes, shapeAliases: S.ALIASES, colors, colorAliases: P.ALIASES, poses,
  stemColor: S.STEM_COLOR, stemShape: S.STEM_SHAPE, cutout: P.CUTOUT }));
"""


def dump():
    return json.loads(subprocess.check_output(["node", "-e", DUMP, str(VENDOR)], text=True))


def num(v):
    s = repr(float(v))
    return s[:-2] if s.endswith(".0") else s


def jstr(s):
    return json.dumps(s)


def nums(a):
    return jstr(",".join(num(x) for x in a))


def render(d):
    L = []
    w = L.append
    w("package com.omarchytv.home;")
    w("")
    w("/*")
    head = [line.rstrip() for line in VENDOR.read_text().split("*/", 1)[0].splitlines()[1:]]
    while head and head[-1] in ("", "*"):
        head.pop()
    L.extend(head)
    w(" */")
    w("")
    w("/**")
    w(" * GENERATED by launcher/tools/gen-grokbot-avatar.py from webos/app/vendor/grokbot/grokbot-avatar.js; do not edit.")
    w(" * Tom Ballard's Grok Bot avatar data (v0.1.0, commit a2efb00, MIT, licence above): the 14 shape outlines")
    w(" * (120 points each, shape units, y down), each shape's two resting eyes {x, y, length, width, angle},")
    w(" * the look table {face x, face y, size, 81 fit values}, aliases, the 11-colour palette and the poses.")
    w(" * Numbers are kept as strings and parsed once, so the class initialiser stays small.")
    w(" */")
    w("final class GrokbotAvatarData {")
    w("    private GrokbotAvatarData() {")
    w("    }")
    w("")
    w("    static final String[] NAMES = {" + ", ".join(jstr(s["name"]) for s in d["shapes"]) + "};")
    w("    static final String[] POINTS = {")
    for s in d["shapes"]:
        w("            " + nums(s["points"]) + ",")
    w("    };")
    w("    static final String[] EYES = {")
    for s in d["shapes"]:
        w("            " + nums(s["eyes"]) + ",")
    w("    };")
    w("    /** face x, face y, size, then the 9 x 9 fit grid. */")
    w("    static final String[] LOOK = {")
    for s in d["shapes"]:
        w("            " + nums(list(s["face"]) + [s["size"]] + list(s["fit"])) + ",")
    w("    };")
    stem = [s for s in d["shapes"] if s["stem"]]
    w("    static final String STEM_SHAPE = " + jstr(d["stemShape"]) + ";")
    w("    static final String STEM_COLOR = " + jstr(d["stemColor"]) + ";")
    w("    static final String STEM = " + nums(stem[0]["stem"]) + ";")
    al = d["shapeAliases"]
    w("    /** alias, shape, alias, shape… */")
    w("    static final String[] SHAPE_ALIASES = {" + ", ".join(jstr(k) + ", " + jstr(al[k]) for k in al) + "};")
    w("    /** name, fill, darkFill (\"\" = none), eye… in his order. */")
    w("    static final String[] COLORS = {")
    for c in d["colors"]:
        w("            " + ", ".join(jstr(c[k]) for k in ("name", "fill", "darkFill", "eye")) + ",")
    w("    };")
    ca = d["colorAliases"]
    w("    static final String[] COLOR_ALIASES = {" + ", ".join(jstr(k) + ", " + jstr(ca[k]) for k in ca) + "};")
    w("    static final String CUTOUT = " + jstr(d["cutout"]) + ";")
    w("    /** name, tilt, height, open… */")
    w("    static final String[] POSES = {")
    for p in d["poses"]:
        w("            " + jstr(p["name"]) + ", " + jstr(num(p["tilt"])) + ", " + jstr(num(p["height"])) + ", " + jstr(num(p["open"])) + ",")
    w("    };")
    w("}")
    return "\n".join(L) + "\n"


def main():
    text = render(dump())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("GrokbotAvatarData.java is out of date: run launcher/tools/gen-grokbot-avatar.py", file=sys.stderr)
            return 1
        print("GrokbotAvatarData.java is up to date")
        return 0
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
