// Off-device only: bundle the unmodified vendored source, then lower all syntax to ES5.
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const babel = require('@babel/standalone');
const acorn = require('acorn');
const root = path.resolve(__dirname, '../../..');
const target = path.join(root, 'launcher/app/src/main/assets/saver/tte-bundle.js');
const bundled = esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'entry.js')], bundle: true, write: false,
  format: 'iife', target: 'esnext', minify: false, legalComments: 'inline'
}).outputFiles[0].text;
const lowered = babel.transform(bundled, {
  babelrc: false, configFile: false, comments: false, compact: true,
  presets: [['env', { targets: { ie: '11' }, modules: false }]]
}).code;
const result = '// Generated by webos/tools/saver-build/build.cjs; tte.js MIT, see tte-js/LICENSE.\n' +
  fs.readFileSync(path.join(__dirname, 'legacy-runtime.js'), 'utf8') + '\n' + lowered + '\n';
acorn.parse(result, { ecmaVersion: 5 });
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== result) throw Error('Stale saver bundle: run node webos/tools/saver-build/build.cjs');
  console.log('Saver bundle is reproducible and parses as ES5.');
} else {
  fs.writeFileSync(target, result);
  console.log('Generated ES5 saver bundle: ' + Buffer.byteLength(result) + ' bytes');
}
