#!/usr/bin/env python3
"""OmarchyTV 2.15 (#47): 1920x1080 copies of the bundled wallpapers, for 1080p TVs.

On a 1080p panel (devicePixelRatio 1) a 3840x2160 background only costs decode time: @tozes measured about 4x faster
decoding and a quicker start with 1080p files on webOS. The webOS app picks webos/app/wallpapers-1080/<theme>/<file>
there (or everywhere with Settings › "Light wallpapers"), else the 4K original. Only files wider than 1920 px get a
copy; WebP q88, as measured in #47. Run after changing launcher/app/src/main/assets/wallpapers. Needs Pillow.
"""
import base64
import io
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "launcher/app/src/main/assets/wallpapers"
OUT = ROOT / "webos/app/wallpapers-1080"


def main() -> None:
    names = []
    for f in sorted(SRC.glob("*/*.webp")):
        b = f.read_bytes()
        if b[:4] == b"UklG":   # some themes ship it base64-wrapped (see webos/build-ipk.sh)
            b = base64.b64decode(b)
        im = Image.open(io.BytesIO(b))
        if im.width <= 1920:
            continue
        im = im.convert("RGB").resize((1920, round(im.height * 1920 / im.width)), Image.LANCZOS)
        rel = f.relative_to(SRC).as_posix()
        dst = OUT / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        im.save(dst, "WEBP", quality=88, method=6)
        names.append(rel)
    (OUT / "index.js").write_text("// generated by webos/tools/wallpapers-1080.py\nwindow.OMARCHY_WP1080 = " + json.dumps(names) + ";\n")
    print(len(names), "copies,", sum((OUT / n).stat().st_size for n in names) // 1024, "KB")


if __name__ == "__main__":
    main()
