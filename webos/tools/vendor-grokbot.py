#!/usr/bin/env python3
"""Vendor Tom Ballard's Grok Bot avatar geometry into the shared webOS/Tizen app.

Usage: python3 webos/tools/vendor-grokbot.py /path/to/omarchy-plugin-grokbot-desktop

Copies qml/shapes.js, qml/palette.js and qml/face.js of his MIT plugin (v0.1.0) unchanged apart from
dropping the QML-only ".pragma library" line, and wraps each in a function scope that exports its names as
window.GrokbotShapes, window.GrokbotPalette and window.GrokbotFace. Output:
webos/app/vendor/grokbot/grokbot-avatar.js (with his MIT licence in the header).
"""
import subprocess
import sys
from pathlib import Path

EXPORTS = {
    "shapes.js": ("GrokbotShapes", ["NAMES", "ROWS", "ALIASES", "SHAPES", "canonical", "known", "resolve", "get",
                                    "eyes", "STEM_COLOR", "STEM_SHAPE", "svgPath", "blend", "alignedPoints",
                                    "look", "stemPoints", "stemLevel"]),
    "palette.js": ("GrokbotPalette", ["NAMES", "OMARCHY", "CUTOUT", "COLORS", "ALIASES", "canonical", "known",
                                      "accepts", "fillFor", "get", "mix"]),
    "face.js": ("GrokbotFace", ["eye", "rotation", "POSES", "pose", "look", "rotatePoints", "mixLook", "fitAt"]),
}

src = Path(sys.argv[1]).resolve()
out = Path(__file__).resolve().parent.parent / "app/vendor/grokbot/grokbot-avatar.js"
commit = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
tag = subprocess.run(["git", "-C", str(src), "describe", "--tags", "--always"], capture_output=True, text=True).stdout.strip()
lic = (src / "LICENSE").read_text(encoding="utf-8").strip()
parts = ["/*\n * Grok Bot avatar geometry, vendored from Tom Ballard's Grok Bot Desktop Companion\n"
         " * https://github.com/tcballard/omarchy-plugin-grokbot-desktop (" + tag + ", commit " + commit + ")\n"
         " * Files: qml/shapes.js, qml/palette.js, qml/face.js, unchanged apart from the QML \".pragma library\"\n"
         " * line; each is wrapped in a function scope (generated by webos/tools/vendor-grokbot.py).\n *\n"
         + "\n".join(" * " + l if l else " *" for l in lic.splitlines()) + "\n */\n"]
for name, (glob, names) in EXPORTS.items():
    body = (src / "qml" / name).read_text(encoding="utf-8")
    body = "\n".join(l for l in body.splitlines() if l.strip() != ".pragma library")
    exp = ", ".join(n + ": (typeof " + n + " !== \"undefined\" ? " + n + " : undefined)" for n in names)
    parts.append("window." + glob + " = (function () {\n" + body + "\nreturn { " + exp + " };\n})();\n")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(parts), encoding="utf-8")
print(out, out.stat().st_size)
